/// Command line arguments parsing.
pub fn cli() -> Command {
    Command::new("languages")
        .about("Collect all the languages of GitHub projects.")
        .long_about(include_str!("../docs/languages.md"))
        .author("Andrea Gilot <andrea.gilot@it.uu.se>")
        .disable_version_flag(true)
        .arg(
            Arg::new("output")
                .short('o')
                .long("output")
                .value_name("OUTPUT_FILE.csv")
                .help("Path to the output csv file to store the metadata. \
                       By default, the name of the output file is the same as the input file with the suffix '.languages.csv'.")
                .required(false)
        )
        .arg(
            Arg::new("input")
                .short('i')
                .long("input")
                .value_name("INPUT_FILE.csv")
                .help("Path to the input csv file to use. It must have a column 'repo_id' with the ids of the projects and a column 'repo_name' with their full names. \
                       Its repository columns are copied to the output, and its other columns are ignored.")
                .required(true)
        )
        .arg(
            Arg::new("tokens")
                .short('t')
                .long("tokens")
                .value_name("TOKENS_FILE.csv")
                .help("Path to the file containing the GitHub tokens to use. It must be a valid CSV file with one column named 'token' and where every line is a \
                       valid GitHub token (e.g ghp_Ab0C1D2eFg3hIjk4LM56oPqRsTuvWX7yZa8B).")
                .required(true)
        )
        .arg(
            Arg::new("cache")
                .short('c')
                .long("cache")
                .value_name("CACHE.csv")
                .help("Path to the cache file to use. Must have been generated by a previous run of this program.")
                .required(false)
        )
        .arg(
            Arg::new("seed")
                .short('s')
                .long("seed")
                .value_name("SEED")
                .help("Seed used to ramdomly shuffle the input data.")
                .default_value("2955615809866670875")
                .value_parser(clap::value_parser!(u64)),
        )
        .arg(
            Arg::new("force")
                .short('f')
                .long("force")
                .help("Override the output file if it already exists.")
                .action(ArgAction::SetTrue),
        )
        .arg(
            Arg::new("infer-source")
                .long("infer-source")
                .help("Infer the source of the projects without one: github if they have an id, local otherwise. \
                       Without this flag, a project without a source is an error.")
                .action(ArgAction::SetTrue),
        )
        .arg(
            Arg::new("sub")
                .long("sub")
                .value_name("NUMBER_OF_PROJECTS")
                .help("Number of projects to sample from the input file. \
                       If not specified, all remaining projects in the input file are used.")
                .value_parser(clap::value_parser!(usize))
        )
        .arg(
            Arg::new("threads")
                .short('n')
                .long("threads")
                .value_name("THREADS")
                .help("Number of projects queried from the GitHub API at the same time.")
                .default_value("1")
                .value_parser(clap::builder::RangedU64ValueParser::<usize>::new().range(1..)),
        )
        .arg(rename_arg())
}

/// Collects the languages of GitHub projects, with the number of bytes written in each of them.
///
/// The input must be a valid CSV file with the ids, the full names and the sources of the projects.
/// Its repository columns are copied to the output, and its other columns are ignored.
/// Projects are queried in a random order.
/// The cache must be the output of a previous run with the same columns, possibly with another input file or seed.
///
/// The output has the repository columns, the link to the projects, and their languages in `languages`.
///
/// # Arguments
///
/// * `input_path` - Path to the input file.
/// * `output_path` - Path to the output file. Defaults to the input path with `.languages.csv` appended.
/// * `tokens` - Path to the file with the GitHub tokens.
/// * `cache_opt` - Path to the cache file, if any.
/// * `seed` - Seed of the random order of the projects.
/// * `force` - Whether to overwrite the output file.
/// * `infer_source` - Whether to infer the source of the projects without one (see [`Repo::from_csv_row`]).
/// * `sub` - Number of projects to query. All the remaining projects if `None`.
/// * `threads` - Number of projects queried from the GitHub API at the same time.
/// * `renames` - Columns of the input read under other names.
/// * `logger` - Logger showing the progress.
pub fn run(
    input_path: &str,
    output_path: Option<&str>,
    tokens: &str,
    cache_opt: Option<&String>,
    seed: u64,
    force: bool,
    infer_source: bool,
    sub: Option<usize>,
    threads: usize,
    renames: &[(String, String)],
    logger: &Logger,
) -> Result<()> {
    // Column index of the id in the output and cache files.
    const ID_COL: usize = 0;

    // Check if the token file is valid and load the tokens.
    let tokens: Vec<String> = logger.log_tokens(tokens)?;

    // Load input file.
    let input_file: DataFrame = logger.run_task("Loading input file", || {
        let df: DataFrame = open_csv(
            input_path,
            Some(Schema::from_iter(RepoColumn::fields())),
            None,
            renames,
        )?;
        require_columns(
            &df,
            input_path,
            &[RepoColumn::RepoId.name(), RepoColumn::RepoName.name()],
        )?;
        ensure!(
            infer_source || has_column(&df, RepoColumn::Source.name()),
            "{input_path} has no column source. Add it, read another column as source with \
             --rename OLD=source, or infer the sources with --infer-source."
        );
        Ok(df)
    })?;

    log_seed(seed);

    let mut shuffled_idx: Vec<usize> = (0..input_file.height()).collect();

    // Load the ids from the input file in random order.
    logger.run_task("Loading project IDs in random order", || {
        let mut rng: StdRng = SeedableRng::seed_from_u64(seed);
        shuffled_idx.shuffle(&mut rng);
        Ok(())
    })?;

    let shuffled_rows = shuffled_idx.into_iter().map(|idx| -> Result<(u32, Repo)> {
        let repo: Repo = Repo::from_csv_row(&input_file, idx, infer_source)?;
        match (repo.id, &repo.name) {
            (Some(id), Some(_)) => Ok((id, repo)),
            _ => bail!("Row {idx} of the input file has no id or no full name"),
        }
    });

    let n_proj: usize = input_file.height();

    info!("  {} projects found.", n_proj);

    // Name of the output file.
    let default_output_path: String = format!("{}.languages.csv", &input_path);
    let output_file_path: &str = output_path.unwrap_or(&default_output_path);

    // Load the previous results.
    let previous_results: HashSet<u32> = if force {
        HashSet::new()
    } else {
        logger.run_task("Resuming progress", || {
            Ok(if Path::new(output_file_path).exists() {
                CSVFile::new(output_file_path, FileMode::Read)?
                    .column(ID_COL)?
                    .into_iter()
                    .collect()
            } else {
                HashSet::new()
            })
        })?
    };

    if !previous_results.is_empty() {
        info!(
            "  the languages of {} projects have already been queried",
            previous_results.len()
        );
    }

    let mut output_file: CSVFile = CSVFile::new(
        output_file_path,
        if force {
            FileMode::Overwrite
        } else {
            FileMode::Append
        },
    )?;

    let header: Vec<&str> = Repo::header()
        .into_iter()
        .chain(ProjectInfo::COLUMNS)
        .collect();
    output_file.write_header(&header)?;

    // Load the cache, whose rows are written as they are.
    let cache: HashMap<u32, Vec<String>> = logger.run_task("Loading cache", || {
        Ok(match cache_opt {
            Some(cache_path) => {
                let cache = CSVFile::new(cache_path, FileMode::Read)?;
                let cache_header: Vec<String> = cache.header()?;
                ensure!(
                    cache_header == header,
                    "The cache {cache_path} has other columns than the output: {} instead of {}",
                    cache_header.join(","),
                    header.join(",")
                );
                cache
                    .extract(|line, record| {
                        let id: u32 = record
                            .get(ID_COL)
                            .and_then(|id| id.parse().ok())
                            .with_context(|| format!("Record {line} of the cache has no id"))?;
                        Ok((id, record.iter().map(str::to_string).collect()))
                    })?
                    .into_iter()
                    .collect()
            }
            None => HashMap::new(),
        })
    })?;

    info!("  {} projects found in the cache.", cache.len());

    // Number of requests that were saved by using the cache.
    let mut request_from_cache: usize = 0;

    let gh = Github::new(tokens);

    // Projects that have not been processed yet, in random order, up to the number of projects to sample.
    let n: usize = sub.unwrap_or(usize::MAX);
    let mut projects: Vec<(u32, Repo)> = Vec::new();
    for row in shuffled_rows {
        if projects.len() == n {
            break;
        }
        let (id, repo): (u32, Repo) = row?;
        if !previous_results.contains(&id) {
            projects.push((id, repo));
        }
    }

    info!("Starting to query the GitHub API...");

    // Create a progress bar
    let progress_bar: ProgressBar = ProgressBar::new(projects.len() as u64);

    progress_bar.set_style(
        indicatif::ProgressStyle::default_bar()
            .template("{elapsed} {wide_bar} {percent}% | Requests from cache: {msg}")?,
    );

    // Rows are written in the order in which the requests complete.
    parallel_pipeline(
        &projects,
        vec![(); threads],
        |_, (id, repo): &(u32, Repo)| {
            // We first check the cache. If the project is not in the cache, we make a request to the API.
            if let Some(row) = cache.get(id) {
                return Ok((row.clone(), true));
            }
            let response: Result<JsonValue, String> = if repo.source == Source::GitHub {
                let full_name: &str = repo.name.as_deref().unwrap_or_default();
                gh.request(&format!(
                    "https://api.github.com/repos/{full_name}/languages"
                ))
                .map_err(|e| e.to_string())
            } else {
                Err(repo.unsupported_source())
            };
            Ok((project_row(repo.clone(), response)?, false))
        },
        |(row, from_cache): (Vec<String>, bool)| {
            output_file.write_record(row)?;
            if from_cache {
                request_from_cache += 1;
            }
            progress_bar.inc(1);
            progress_bar.set_message(request_from_cache.to_string());
            Ok(())
        },
    )?;
    output_file.flush()?;
    Ok(())
}

/// Returns the row of a project in the output.
///
/// # Arguments
///
/// * `repo` - The project.
/// * `response` - The response of the GitHub API about the languages of the project, or the error message.
///   On an error, the name of the project is replaced by the error message, and the link is empty.
fn project_row(mut repo: Repo, response: Result<JsonValue, String>) -> Result<Vec<String>> {
    let info: ProjectInfo = match response {
        Ok(languages) => ProjectInfo::from_json(&languages)?,
        Err(error) => {
            repo.name = Some(error);
            ProjectInfo::default()
        }
    };
    Ok(repo.row().into_iter().chain(info.values()).collect())
}

/// Represents the information retrieved from a GitHub project.
///
/// # Fields
///
/// * languages: A map from the name of each language to the total size of the files written in that language.
///
#[derive(Default)]
struct ProjectInfo {
    languages: HashMap<String, i64>,
}

impl ProjectInfo {
    /// Columns of the languages, after the repository columns and the link.
    const COLUMNS: [&'static str; 1] = ["languages"];

    /// Returns the values of the languages, in the order of [`Self::COLUMNS`].
    fn values(&self) -> Vec<String> {
        vec![Self::print_languages(&self.languages)]
    }

    /// Parses a JSON object into a ProjectInfo instance.
    ///
    /// # Arguments
    ///
    /// * `json` - The JSON object to parse.
    ///
    /// # Returns
    ///
    /// An option containing the ProjectInfo instance if the JSON object could be parsed.
    ///
    /// # Panics
    ///
    /// * If the JSON object could not be parsed.
    fn from_json(json_lang: &json::JsonValue) -> Result<Self> {
        let mut languages: HashMap<String, i64> = HashMap::new();
        for (lan, size) in json_lang.entries() {
            languages.insert(
                lan.to_owned(),
                size.as_i64()
                    .with_context(|| anyhow!("Could not parse the size of the language {lan}"))?,
            );
        }

        Ok(Self { languages })
    }

    /// Returns a string representation of the language map. Each entry is separated by a semicolon to avoid conflicts with the CSV format.
    /// Languages are sorted by decreasing size, then by name, so that the output is the same in every run.
    ///
    /// # Arguments
    ///
    /// * `languages` - The map from the name of each language to the total size of the files written in that language.
    ///
    /// # Example
    ///
    /// `languages = {"Rust": 1000, "Python": 500} -> "Rust:1000;Python:500"`
    fn print_languages(languages: &HashMap<String, i64>) -> String {
        let mut by_size: Vec<(&String, &i64)> = languages.iter().collect();
        by_size.sort_by(|(name_a, size_a), (name_b, size_b)| {
            size_b.cmp(size_a).then(name_a.cmp(name_b))
        });
        by_size
            .into_iter()
            .map(|(k, v)| format!("{k}:{v}"))
            .collect::<Vec<String>>()
            .join(";")
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use anyhow::ensure;

    const TEST_DATA: &str = "tests/data/phases/languages";

    #[test]
    fn languages_are_sorted_by_size_then_name() {
        let languages: HashMap<String, i64> = HashMap::from([
            ("Python".to_string(), 53),
            ("C".to_string(), 53),
            ("Java".to_string(), 253),
        ]);
        assert_eq!(
            ProjectInfo::print_languages(&languages),
            "Java:253;C:53;Python:53"
        );
    }

    /// Returns a repository on GitHub, with a license and a commit.
    fn repo() -> Repo {
        Repo {
            id: Some(42),
            source: Source::GitHub,
            name: Some("owner/repo".to_string()),
            license: Some("MIT License".to_string()),
            commit: Some("abc123".to_string()),
        }
    }

    #[test]
    fn rows_of_queried_projects() -> Result<()> {
        let languages = json::parse(r#"{"Rust": 100, "C": 300}"#)?;
        assert_eq!(
            project_row(repo(), Ok(languages.clone()))?,
            [
                "42",
                "github",
                "owner/repo",
                "MIT License",
                "abc123",
                "https://github.com/owner/repo/tree/abc123",
                "C:300;Rust:100"
            ]
        );
        // Without a commit, the link is the page of the repository.
        let unpinned = Repo {
            commit: None,
            ..repo()
        };
        assert_eq!(
            project_row(unpinned, Ok(languages))?[4..6],
            ["", "https://github.com/owner/repo"]
        );
        Ok(())
    }

    #[test]
    fn rows_of_failed_queries() -> Result<()> {
        // The name is replaced by the error, and the link is empty.
        assert_eq!(
            project_row(repo(), Err("http/2 404".to_string()))?,
            [
                "42",
                "github",
                "http/2 404",
                "MIT License",
                "abc123",
                "",
                ""
            ]
        );
        Ok(())
    }

    #[test]
    #[ignore = "requires network access and valid GitHub tokens"]
    fn test_language_scraper() -> Result<()> {
        let input_file: String = format!("{TEST_DATA}/repos.csv");
        let output_file: String = format!("{input_file}.languages.csv");
        ensure!(std::path::Path::new(&input_file).exists());

        delete_file(&output_file, true)?;

        let tokens_file: String = "ghtokens.csv".to_string();

        run(
            &input_file,
            None,
            &tokens_file,
            None,
            0,
            false,
            false,
            None,
            1,
            &[],
            test_logger(),
        )?;

        delete_file(&output_file, false)
    }

    #[test]
    fn missing_tokens_languages() {
        let result = run(
            &format!("{TEST_DATA}/repos.csv"),
            None,
            "nonexistent_tokens.csv",
            None,
            0,
            false,
            false,
            None,
            1,
            &[],
            test_logger(),
        );
        assert!(result.is_err());
    }
}
