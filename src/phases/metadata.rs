/// Command line arguments parsing.
pub fn cli() -> Command {
    Command::new("metadata")
        .about("Collect the metadata of GitHub projects")
        .long_about(include_str!("../docs/metadata.md"))
        .author("Andrea Gilot <andrea.gilot@it.uu.se>")
        .disable_version_flag(true)
        .arg(
            Arg::new("output")
                .short('o')
                .long("output")
                .value_name("OUTPUT_FILE.csv")
                .help("Path to the output csv file to store the metadata. \
                       By default, the name of the output file is the same as the input file with the suffix '.metadata.csv'.")
                .required(false)
        )
        .arg(
            Arg::new("input")
                .short('i')
                .long("input")
                .value_name("INPUT_FILE.csv")
                .help("Path to the input csv file to use. It must have a column 'repo_id' with the ids of the projects and a column 'repo_name' with their full names. \
                       Its repository columns are copied to the output, and its other columns are ignored.")
                .required(true)
        )
        .arg(
            Arg::new("tokens")
                .short('t')
                .long("tokens")
                .value_name("TOKENS_FILE.csv")
                .help("Path to the file containing the GitHub tokens to use. It must be a valid CSV file with one column named 'token' and where every line is a \
                       valid GitHub token (e.g ghp_Ab0C1D2eFg3hIjk4LM56oPqRsTuvWX7yZa8B).")
                .required(true)
        )
        .arg(
            Arg::new("cache")
                .short('c')
                .long("cache")
                .value_name("CACHE.csv")
                .help("Path to the cache file to use. Must have been generated by a previous run of this program.")
                .required(false)
        )
        .arg(
            Arg::new("seed")
                .short('s')
                .long("seed")
                .value_name("SEED")
                .help("Seed used to randomly shuffle the input data.")
                .default_value("2955615809866670875")
                .value_parser(clap::value_parser!(u64)),
        )
        .arg(
            Arg::new("force")
                .short('f')
                .long("force")
                .help("Override the output file if it already exists.")
                .action(ArgAction::SetTrue),
        )
        .arg(
            Arg::new("infer-source")
                .long("infer-source")
                .help("Infer the source of the projects without one: github if they have an id, local otherwise. \
                       Without this flag, a project without a source is an error.")
                .action(ArgAction::SetTrue),
        )
        .arg(
            Arg::new("sub")
                .long("sub")
                .value_name("NUMBER_OF_PROJECTS")
                .help("Number of projects to sample from the input file. \
                       If not specified, all remaining projects in the input file are used.")
                .value_parser(clap::value_parser!(usize))
        )
        .arg(
            Arg::new("threads")
                .short('n')
                .long("threads")
                .value_name("THREADS")
                .help("Number of requests sent to the GitHub API at the same time.")
                .default_value("1")
                .value_parser(clap::builder::RangedU64ValueParser::<usize>::new().range(1..)),
        )
        .arg(rename_arg())
}

/// Collects metadata about GitHub projects.
///
/// The input must be a valid CSV file with the ids, the full names and the sources of the projects.
/// Its repository columns are copied to the output, and its other columns are ignored.
/// Such a file can be obtained with the `ids` command. Projects are queried in a random order.
/// The cache must be the output of a previous run with the same columns, possibly with another input file or seed.
///
/// The output has the repository columns, with the license of the projects in `repo_license`,
/// the link to the projects, and their metadata (main language, dates, stars, forks, issues, size, ...).
///
/// # Arguments
///
/// * `input_path` - Path to the input file.
/// * `output_path` - Path to the output file. Defaults to the input path with `.metadata.csv` appended.
/// * `tokens` - Path to the file with the GitHub tokens.
/// * `cache_opt` - Path to the cache file, if any.
/// * `seed` - Seed of the random order of the projects.
/// * `force` - Whether to overwrite the output file.
/// * `infer_source` - Whether to infer the source of the projects without one (see [`Repo::from_csv_row`]).
/// * `sub` - Number of projects to query. All the remaining projects if `None`.
/// * `threads` - Number of requests sent to the GitHub API at the same time.
/// * `renames` - Columns of the input read under other names.
/// * `logger` - Logger showing the progress.
pub fn run(
    input_path: &str,
    output_path: Option<&String>,
    tokens: &str,
    cache_opt: Option<&String>,
    seed: u64,
    force: bool,
    infer_source: bool,
    sub: Option<usize>,
    threads: usize,
    renames: &[(String, String)],
    logger: &Logger,
) -> Result<()> {
    // Column index of the id in the output and cache files.
    const ID_COL: usize = 0;

    // Check if the token file is valid and load the tokens.
    let tokens: Vec<String> = logger.log_tokens(tokens)?;

    // Load input file.
    let input_file: DataFrame = logger.run_task("Loading input file", || {
        let df: DataFrame = open_csv(
            input_path,
            Some(Schema::from_iter(RepoColumn::fields())),
            None,
            renames,
        )?;
        require_columns(
            &df,
            input_path,
            &[RepoColumn::RepoId.name(), RepoColumn::RepoName.name()],
        )?;
        ensure!(
            infer_source || has_column(&df, RepoColumn::Source.name()),
            "{input_path} has no column source. Add it, read another column as source with \
             --rename OLD=source, or infer the sources with --infer-source."
        );
        Ok(df)
    })?;

    log_seed(seed);

    let mut shuffled_idx: Vec<usize> = (0..input_file.height()).collect();

    // Load the ids from the input file in random order.
    logger.run_task("Loading project IDs in random order", || {
        let mut rng: StdRng = SeedableRng::seed_from_u64(seed);
        shuffled_idx.shuffle(&mut rng);
        Ok(())
    })?;

    let shuffled_rows = shuffled_idx.into_iter().map(|idx| -> Result<(u32, Repo)> {
        let repo: Repo = Repo::from_csv_row(&input_file, idx, infer_source)?;
        match (repo.id, &repo.name) {
            (Some(id), Some(_)) => Ok((id, repo)),
            _ => bail!("Row {idx} of the input file has no id or no full name"),
        }
    });

    let n_proj: usize = input_file.height();

    info!("  {} projects found.", n_proj);

    // Name of the output file.
    let default_output_path: String = format!("{}.metadata.csv", &input_path);
    let output_file_path: &str = output_path.unwrap_or(&default_output_path);

    // Load the previous results.
    let previous_results: HashSet<u32> = if force {
        HashSet::new()
    } else {
        logger.run_task("Resuming progress", || {
            Ok(if Path::new(output_file_path).exists() {
                CSVFile::new(output_file_path, FileMode::Read)?
                    .column(ID_COL)?
                    .into_iter()
                    .collect()
            } else {
                HashSet::new()
            })
        })?
    };

    if !previous_results.is_empty() {
        info!(
            "  the metadata of {} projects have already been queried",
            previous_results.len()
        );
    }

    let mut output_file: CSVFile = CSVFile::new(
        output_file_path,
        if force {
            FileMode::Overwrite
        } else {
            FileMode::Append
        },
    )?;

    let header: Vec<&str> = Repo::header()
        .into_iter()
        .chain(ProjectMetadata::COLUMNS)
        .collect();
    output_file.write_header(&header)?;

    // Load the cache, whose rows are written as they are.
    let cache: HashMap<u32, Vec<String>> = logger.run_task("Loading cache", || {
        Ok(match cache_opt {
            Some(cache_path) => {
                let cache = CSVFile::new(cache_path, FileMode::Read)?;
                let cache_header: Vec<String> = cache.header()?;
                ensure!(
                    cache_header == header,
                    "The cache {cache_path} has other columns than the output: {} instead of {}",
                    cache_header.join(","),
                    header.join(",")
                );
                cache
                    .extract(|line, record| {
                        let id: u32 = record
                            .get(ID_COL)
                            .and_then(|id| id.parse().ok())
                            .with_context(|| format!("Record {line} of the cache has no id"))?;
                        Ok((id, record.iter().map(str::to_string).collect()))
                    })?
                    .into_iter()
                    .collect()
            }
            None => HashMap::new(),
        })
    })?;

    info!("  {} projects found in the cache.", cache.len());

    // Number of requests that were saved by using the cache.
    let mut request_from_cache: usize = 0;

    let gh = Github::new(tokens);

    // Projects that have not been processed yet, in random order, up to the number of projects to sample.
    let n: usize = sub.unwrap_or(usize::MAX);
    let mut projects: Vec<(u32, Repo)> = Vec::new();
    for row in shuffled_rows {
        if projects.len() == n {
            break;
        }
        let (id, repo): (u32, Repo) = row?;
        if !previous_results.contains(&id) {
            projects.push((id, repo));
        }
    }

    info!("Starting to query the GitHub API...");

    // Create a progress bar
    let progress_bar: ProgressBar = ProgressBar::new(projects.len() as u64);

    progress_bar.set_style(
        indicatif::ProgressStyle::default_bar()
            .template("{elapsed} {wide_bar} {percent}% | Requests from cache: {msg}")?,
    );

    // Rows are written in the order in which the requests complete.
    parallel_pipeline(
        &projects,
        vec![(); threads],
        |_, (id, repo): &(u32, Repo)| {
            // We first check the cache. If the project is not in the cache, we make a request to the API.
            if let Some(row) = cache.get(id) {
                return Ok((row.clone(), true));
            }
            let response: Result<JsonValue, String> = if repo.source == Source::GitHub {
                let full_name: &str = repo.name.as_deref().unwrap_or_default();
                gh.request(&format!("https://api.github.com/repos/{full_name}"))
                    .map_err(|e| e.to_string())
            } else {
                Err(repo.unsupported_source())
            };
            Ok((project_row(repo.clone(), response)?, false))
        },
        |(row, from_cache): (Vec<String>, bool)| {
            output_file.write_record(row)?;
            if from_cache {
                request_from_cache += 1;
            }
            progress_bar.inc(1);
            progress_bar.set_message(request_from_cache.to_string());
            Ok(())
        },
    )?;
    output_file.flush()?;
    Ok(())
}

/// Returns the row of a project in the output.
///
/// # Arguments
///
/// * `repo` - The project.
/// * `response` - The response of the GitHub API about the project, or the error message.
///   On an error, the name of the project is replaced by the error message, and the link is empty.
fn project_row(mut repo: Repo, response: Result<JsonValue, String>) -> Result<Vec<String>> {
    Ok(match response {
        Ok(json) => {
            let metadata = ProjectMetadata::parse_json(&json, ())?;
            repo.license = Some(metadata.license.clone());
            repo.row().into_iter().chain(metadata.values()).collect()
        }
        Err(error) => {
            repo.name = Some(error);
            repo.values()
                .into_iter()
                .chain([String::new()])
                .chain(ProjectMetadata::default().values())
                .collect()
        }
    })
}

/// Represents the metadata of a GitHub project.
/// The description of the project and the homepage are omitted as they can produce errors in the CSV file.
struct ProjectMetadata {
    /// The main language of the project.
    language: String,
    /// The timestamp of the creation of the project.
    created: i64,
    /// The timestamp of the last push to the project.
    pushed: i64,
    /// The timestamp of the last update of the project.
    updated: i64,
    /// Whether the project is a fork.
    fork: bool,
    /// Whether the project is disabled.
    disabled: bool,
    /// Whether the project is archived.
    archived: bool,
    /// The number of stars of the project.
    stars: u32,
    /// The number of times the project has been forked.
    forks: u32,
    /// The number of open issues of the project.
    issues: u32,
    /// Whether the project has issue tracking enabled (different from having 0 issues).
    has_issues: bool,
    /// The number of watchers of the project.
    watchers_count: u32,
    /// The number of subscribers of the project.
    subscribers: u32,
    /// The size of the project in LOC.
    size: u64,
    /// The name of the license of the project, written in `repo_license`.
    license: String,
}

/// Default implementation for ProjectMetadata.
/// Sets all the dates to 1970-01-01T00:00:00Z, the booleans to false, the numbers to 0 and the strings to empty.
impl Default for ProjectMetadata {
    fn default() -> Self {
        Self {
            language: String::new(),
            created: 0,
            pushed: 0,
            updated: 0,
            fork: false,
            disabled: false,
            archived: false,
            stars: 0,
            forks: 0,
            issues: 0,
            has_issues: false,
            watchers_count: 0,
            subscribers: 0,
            size: 0,
            license: String::new(),
        }
    }
}

impl ProjectMetadata {
    /// Columns of the metadata, after the repository columns and the link.
    const COLUMNS: [&'static str; 14] = [
        "language",
        "created",
        "pushed",
        "updated",
        "fork",
        "disabled",
        "archived",
        "stars",
        "forks",
        "issues",
        "has_issues",
        "watchers_count",
        "subscribers",
        "size",
    ];

    /// Returns the values of the metadata, in the order of [`Self::COLUMNS`].
    fn values(&self) -> Vec<String> {
        vec![
            self.language.clone(),
            self.created.to_string(),
            self.pushed.to_string(),
            self.updated.to_string(),
            u8::from(self.fork).to_string(),
            u8::from(self.disabled).to_string(),
            u8::from(self.archived).to_string(),
            self.stars.to_string(),
            self.forks.to_string(),
            self.issues.to_string(),
            u8::from(self.has_issues).to_string(),
            self.watchers_count.to_string(),
            self.subscribers.to_string(),
            self.size.to_string(),
        ]
    }
}

impl FromGitHub for ProjectMetadata {
    type Complement = ();
    fn parse_json(json: &JsonValue, _complement: ()) -> Result<Self> {
        let language: String = if !json["language"].is_null() {
            get_field::<String>(json, "language")?
        } else {
            String::new()
        };
        let created: i64 = Self::parse_date_time(json, "created_at")?;
        let pushed: i64 = Self::parse_date_time(json, "pushed_at")?;
        let updated: i64 = Self::parse_date_time(json, "updated_at")?;
        let fork = get_field::<bool>(json, "fork")?;
        let disabled = get_field::<bool>(json, "disabled")?;
        let archived = get_field::<bool>(json, "archived")?;
        let stars = get_field::<u32>(json, "stargazers_count")?;
        let forks = get_field::<u32>(json, "forks_count")?;
        let issues = get_field::<u32>(json, "open_issues_count")?;
        let has_issues = get_field::<bool>(json, "has_issues")?;
        let watchers_count = get_field::<u32>(json, "watchers_count")?;
        let subscribers = get_field::<u32>(json, "subscribers_count")?;
        let size = get_field::<u64>(json, "size")?;

        // Parse the license field, defaulting to "unknown" if not present.
        let license = if !json["license"].is_null() {
            get_field::<String>(&json["license"], "name")?
        } else {
            "unknown".to_string()
        };

        // Return a new ProjectMetadata instance with the parsed data.
        Ok(Self {
            language,
            created,
            pushed,
            updated,
            fork,
            disabled,
            archived,
            stars,
            forks,
            issues,
            has_issues,
            watchers_count,
            subscribers,
            size,
            license,
        })
    }
}

#[cfg(test)]
mod tests {
    use anyhow::ensure;

    use super::*;
    use crate::utils::{dataframes::has_column, logger::test_logger};
    use polars::prelude::SortMultipleOptions;

    const TEST_DATA: &str = "tests/data/phases/metadata";

    #[test]
    #[ignore = "requires network access and valid GitHub tokens"]
    fn test_language_scraper() -> Result<()> {
        let input_file: String = format!("{TEST_DATA}/repos.csv");
        let output_file: String = format!("{input_file}.metadata.csv");
        ensure!(
            std::path::Path::new(&input_file).exists(),
            "Input file does not exist"
        );
        delete_file(&output_file, true)?;

        let tokens_file: String = "ghtokens.csv".to_string();

        run(
            &input_file,
            None,
            &tokens_file,
            None,
            0,
            false,
            false,
            None,
            1,
            &[],
            test_logger(),
        )?;

        let output_df = open_csv(&output_file, None, None, &[])?;
        ensure!(
            has_column(&output_df, RepoColumn::RepoName.name()),
            "Output does not have 'repo_name' column"
        );
        let sorted_output_df = output_df.sort(
            vec![RepoColumn::RepoName.name()],
            SortMultipleOptions::new(),
        )?;

        let expected_df = open_csv(&format!("{output_file}.expected"), None, None, &[])?;
        ensure!(
            has_column(&expected_df, RepoColumn::RepoName.name()),
            "Expected output does not have 'repo_name' column"
        );
        let sorted_expected_df = expected_df.sort(
            vec![RepoColumn::RepoName.name()],
            SortMultipleOptions::new(),
        )?;

        assert_eq!(sorted_expected_df, sorted_output_df);

        delete_file(&output_file, false)
    }

    /// Returns a repository on GitHub, without license nor commit.
    fn repo() -> Repo {
        Repo {
            id: Some(42),
            source: Source::GitHub,
            name: Some("owner/repo".to_string()),
            license: None,
            commit: None,
        }
    }

    #[test]
    fn rows_of_queried_projects() -> Result<()> {
        let json = json::parse(
            r#"{
                "language": "Rust", "created_at": "2024-01-01T00:00:00Z",
                "pushed_at": "2024-01-02T00:00:00Z", "updated_at": "2024-01-03T00:00:00Z",
                "fork": false, "disabled": false, "archived": true, "stargazers_count": 5,
                "forks_count": 1, "open_issues_count": 2, "has_issues": true,
                "watchers_count": 5, "subscribers_count": 3, "size": 10,
                "license": {"name": "MIT License"}
            }"#,
        )?;
        let row: Vec<String> = project_row(repo(), Ok(json))?;
        assert_eq!(
            row.len(),
            Repo::header().len() + ProjectMetadata::COLUMNS.len()
        );
        assert_eq!(
            row[..7],
            [
                "42",
                "github",
                "owner/repo",
                "MIT License",
                "",
                "https://github.com/owner/repo",
                "Rust"
            ]
        );
        Ok(())
    }

    #[test]
    fn rows_of_failed_queries() -> Result<()> {
        let row: Vec<String> = project_row(repo(), Err("http/2 404".to_string()))?;
        // The name is replaced by the error, and the link is empty.
        assert_eq!(row[..6], ["42", "github", "http/2 404", "", "", ""]);
        Ok(())
    }

    #[test]
    fn missing_tokens_metadata() {
        let result = run(
            &format!("{TEST_DATA}/repos.csv"),
            None,
            "nonexistent_tokens.csv",
            None,
            0,
            false,
            false,
            None,
            1,
            &[],
            test_logger(),
        );
        assert!(result.is_err());
    }
}
